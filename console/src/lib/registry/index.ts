import type { ResourceConfig } from "$lib/framework/types";

const registry = new Map<string, ResourceConfig>();

export function registerResource(config: ResourceConfig) {
  registry.set(`${config.module}.${config.key}`, config);
}

export function getResource(module: string, key: string): ResourceConfig | undefined {
  return registry.get(`${module}.${key}`);
}

export function getModuleResources(module: string): ResourceConfig[] {
  return Array.from(registry.values()).filter((r) => r.module === module);
}

